"""Bake the room scene into the RetroArch Background texture for crt-decoupled-xinghui.slangp:
background -> tv_frame -> props (everything the shader shows OUTSIDE its frame; the tube, bezel and frame
themselves are drawn by decoupled/dc-composite-xinghui.slang), plus its SpillMask (make_spill). Also prints the
preset's DC_* lines, and writes tools/asset-xinghui.js (git-ignored) for CRT Studio's "XINGHUI room" preset button.
usage: python export_ra.py [--studio-only]   (--studio-only: just refresh the studio asset from the baked textures)"""
import base64
import json
import os
import sys
from PIL import Image
from dc_params import DC, BEZEL

TEX = os.path.join(os.path.dirname(__file__), "..", "decoupled", "textures")
OUT = os.path.join(TEX, "xinghui-room-bg.png")
SPILL = os.path.join(TEX, "xinghui-room-spill.png")
STUDIO = os.path.join(os.path.dirname(__file__), "..", "tools", "asset-xinghui.js")


def write_studio_asset():
    """The baked textures as data URIs (a file:// page can't texture a file:// image) + the scene's params."""
    uri = lambda p: "data:image/png;base64," + base64.b64encode(open(p, "rb").read()).decode()
    params = [f"{k} {v}" for k, v in DC.items()] + [f"#define {k} {v}" for k, v in BEZEL.items()]
    params_js = json.dumps("\n".join(params))
    lines = ["// GENERATED by art/export_ra.py: the XINGHUI room for tools/crt-studio.html (not versioned)",
             f'window.XINGHUI_BG="{uri(OUT)}";',
             f'window.XINGHUI_MASK="{uri(SPILL)}";',
             f"window.XINGHUI_PARAMS={params_js};"]
    with open(STUDIO, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", os.path.normpath(STUDIO))


if __name__ == "__main__":
    if "--studio-only" in sys.argv:
        write_studio_asset()
        sys.exit()
    bg = Image.open("out/background.png").convert("RGBA")
    for layer in ("out/tv_frame.png", "out/props.png"):
        bg.alpha_composite(Image.open(layer).convert("RGBA"))
    bg.convert("RGB").save(OUT, optimize=True)
    print("wrote", os.path.normpath(OUT))
    import make_spill                                   # TV-light receptivity of the same art (SpillMask)
    Image.fromarray(make_spill.build(), "RGB").save(SPILL, optimize=True)
    print("wrote", os.path.normpath(SPILL))
    for k, v in DC.items():
        print(f'{k} = "{v:.6f}"')
    write_studio_asset()
