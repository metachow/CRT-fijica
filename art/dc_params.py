"""Shader parameters for the XINGHUI room scene, derived from common.py's screen geometry so the art and the
shader can't drift apart. Prints the DC_* runtime params (preset) and the bezel #defines (dc-composite-xinghui).
The bezel look is a first guess at the TV's silver plastic — fine-tune it in tools/crt-studio.html (BG tab: load
out/xinghui_bg.png as a layer below the tube) and paste the export back."""
import os
from make_bg import CAB_TOP
from common import W, H, SCREEN_CENTER, TUBE_H, TUBE_ASPECT, BZL_W, BZL_WX, FRM_W, FRM_WX, shader_frame

DC = dict(
    DC_SCALE=TUBE_H / H,
    DC_POS_X=SCREEN_CENTER[0] / W,
    DC_POS_Y=SCREEN_CENTER[1] / H,           # from the top, like RA's vTexCoord
    DC_ASPECT=TUBE_ASPECT,
    DC_CURVE_X=0.004,                        # 数码超平 = a flat-face tube: barely any barrel
    DC_CURVE_Y=0.006,
    DC_CORNER=0.012,
    DC_BG_ON=1.0,
    DC_FG_ON=0.0,
)

BEZEL = dict(
    BZL_WIDTH=BZL_W, BZL_WIDTH_X=BZL_WX, FRM_WIDTH=FRM_W, FRM_WIDTH_X=FRM_WX,
    BZL_OUTER_CORNER=0.004, FRM_OUTER_CORNER=0.012,
    # the set's silver-beige moulded plastic, as measured on the housing art face-on
    BZL_COLOR_HUE=43.0, BZL_COLOR_SAT=7.0, BZL_COLOR_VAL=0.73, BZL_NOISE=0.04,
    BZL_GLOSS=0.10, BZL_SHINE=60.0,            # satin moulded plastic
    FRM_USE_INDEP_COLOR=0,                     # frame = same plastic as the bezel
    # the room's key light: upper-left, fairly high (cf. make_tv / make_bg shading)
    LIGHT_ANGLE=135.0, LIGHT_ELEV=55.0, AMBIENT=0.45, BZL_SLOPE=28.0,
    # make_tv paints the housing face under a soft upper-left lamp (brighter up, darker right); the shader's flat
    # frame must follow the same falloff or it reads tilted (raised at the bottom-right, sunk at the top-left).
    # Plane fitted to the housing ring just outside shader_frame(): per tube height, right -0.087, up +0.269.
    LIGHT_GRAD_X=-0.087, LIGHT_GRAD_Y=0.269,
    LIP_WIDTH=0.005, LIP_ROLL=70.0, BZL_EDGE_W=0.003,
    # the screen surround sits IN the housing (housing face -> step down -> frame -> slope -> tube): the frame's
    # outer edge is the housing rising around it, so it turns TOWARD the tube. A raised-plate roll (> 0) lit the
    # top-left rim and darkened the bottom-right one, reading as raised on the left / sunk on the right.
    FRM_EDGE_W=0.004, FRM_EDGE_ROLL=-50.0,
    # the miters of this recessed bezel are valleys: a bright seam read as a raised ridge at the bottom-right
    # corner (both faces lit by the upper-left light) -> no seam highlight, a little valley occlusion instead
    CREASE_STR=0.10,
    REFL_STR=0.18,
    # the varnished cabinet top mirrors the picture (SpillMask G = where); flip line = the set's base
    GLOSS_STR=0.40,                            # Fresnel of varnish at the scene's ~10 deg grazing view
    GLOSS_MIRROR_Y=round(CAB_TOP / H, 4),
    GLOSS_STRETCH=3.2,                         # true geometry (1) shows only the housing's foot: the top is
                                               # ~16 cm deep, the tube starts ~7 cm up -> seen from ~30 deg
    GLOSS_BLUR=0.15,
)

SHADER = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "decoupled", "dc-composite-xinghui.slang")


def write_shader():
    """Regenerate the XINGHUI dc-composite wrapper from BEZEL."""
    lines = ["#version 450",
             "// =============================================================================",
             "//  dc-composite pass, XINGHUI look: the sloped bezel + flat frame of the 2000s",
             "//  silver-beige consumer TV in the room scene (art/make_tv.py leaves the screen",
             "//  area as plain housing). GENERATED by art/dc_params.py — edit BEZEL there",
             "//  (or tune in tools/crt-studio.html and copy the values back), then re-run it.",
             "// ============================================================================="]
    lines += [f"#define {k:<24}{v}" for k, v in BEZEL.items()]
    lines.append('#include "dc-composite.inc"')
    with open(SHADER, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    return os.path.normpath(SHADER)


if __name__ == "__main__":
    print("# frame outer edge (px):", [round(v) for v in shader_frame()])
    print("# ---- preset (runtime params)")
    for k, v in DC.items():
        print(f'{k} = "{v:.6f}"')
    print("# wrote", write_shader())
